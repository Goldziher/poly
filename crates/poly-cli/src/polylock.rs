//! `poly.lock` — the single lock file for remote `extends` bases, Git hook
//! sources and downloadable tool releases (ADR 0038, ADR 0046). It replaces `poly-config.lock` and `poly-hooks.lock`.
//!
//! Entries are kept in a deterministic order so a re-lock of unchanged inputs
//! rewrites the file byte for byte.

use std::path::Path;

use anyhow::{Context, bail};
use serde::{Deserialize, Serialize};

pub use poly_config::tool_lock::{LockedAsset, LockedTool};

/// Repo-root lock file name.
pub const LOCK_FILE_NAME: &str = "poly.lock";

/// Lock files that `poly.lock` replaced; read by nothing, named only in hints.
const LEGACY_LOCK_FILE_NAMES: [&str; 2] = ["poly-config.lock", "poly-hooks.lock"];

/// The only supported lock schema version.
pub const LOCK_VERSION: u32 = 1;

const HEADER: &str = "# Generated by `poly lock`. Do not edit by hand.\n";

/// A remote `extends` base whose symbolic revision is pinned to an object ID.
///
/// Keyed by `(git, file, revision)`: the declared repository URL, the file read
/// from it, and the declared symbolic revision. `locked` is the full object ID.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LockedExtends {
    /// Repository URL of the base.
    pub git: String,
    /// File read from the base repository.
    pub file: String,
    /// Declared symbolic revision (branch/tag/`HEAD`) that was locked.
    pub revision: String,
    /// Full object ID `revision` resolved to.
    pub locked: String,
}

/// A Git hook source pinned to a resolved revision.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LockedHookSource {
    /// Source identifier from `[[hooks.sources]]`.
    pub id: String,
    /// Repository URL of the source.
    pub source: String,
    /// Full object ID the declared revision resolved to.
    pub revision: String,
    /// Cache location of the checkout.
    pub path: String,
}

/// The parsed `poly.lock`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PolyLock {
    /// Lock schema version (always [`LOCK_VERSION`]).
    pub version: u32,
    /// Locked remote `extends` bases.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub extends: Vec<LockedExtends>,
    /// Locked Git hook sources.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub hook_sources: Vec<LockedHookSource>,
    /// Downloadable `[tools]` pinned to a release, with every platform's SHA-256.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub tools: Vec<LockedTool>,
}

impl Default for PolyLock {
    fn default() -> Self {
        PolyLock {
            version: LOCK_VERSION,
            extends: Vec::new(),
            hook_sources: Vec::new(),
            tools: Vec::new(),
        }
    }
}

impl PolyLock {
    /// Whether the lock records nothing (such a lock is never written to disk).
    pub fn is_empty(&self) -> bool {
        self.extends.is_empty() && self.hook_sources.is_empty() && self.tools.is_empty()
    }

    /// The locked object ID for an `(git, file, revision)` key, if recorded.
    pub fn locked_oid(&self, git: &str, file: &str, revision: &str) -> Option<&str> {
        self.extends
            .iter()
            .find(|entry| entry.git == git && entry.file == file && entry.revision == revision)
            .map(|entry| entry.locked.as_str())
    }

    /// The locked entry for a hook source `(id, url)`, if recorded.
    pub fn hook_source(&self, id: &str, url: &str) -> Option<&LockedHookSource> {
        self.hook_sources
            .iter()
            .find(|entry| entry.id == id && entry.source == url)
    }

    /// Sort every table into its canonical order.
    pub fn normalize(&mut self) {
        self.extends
            .sort_by(|a, b| (&a.git, &a.file, &a.revision, &a.locked).cmp(&(&b.git, &b.file, &b.revision, &b.locked)));
        self.hook_sources
            .sort_by(|a, b| (&a.id, &a.source, &a.revision).cmp(&(&b.id, &b.source, &b.revision)));
        self.tools.sort_by(|a, b| a.name.cmp(&b.name));
        for tool in &mut self.tools {
            tool.assets.sort_by(|a, b| a.platform.cmp(&b.platform));
        }
    }

    /// The locked entry for the tool called `name`, if recorded.
    pub fn tool(&self, name: &str) -> Option<&LockedTool> {
        self.tools.iter().find(|entry| entry.name == name)
    }

    /// Render the canonical file text (normalized order, generated header).
    pub fn to_toml(&self) -> anyhow::Result<String> {
        let mut canonical = self.clone();
        canonical.normalize();
        let body = toml::to_string_pretty(&canonical).context("serializing poly.lock")?;
        Ok(format!("{HEADER}{body}"))
    }
}

/// Read `<root>/poly.lock`, or `None` when it does not exist. The result is
/// normalized. Only `poly.lock` is read; the legacy lock files are ignored here
/// and surfaced through [`legacy_hint`] when an entry turns out to be missing.
pub fn read(root: &Path) -> anyhow::Result<Option<PolyLock>> {
    let path = root.join(LOCK_FILE_NAME);
    if !path.is_file() {
        return Ok(None);
    }
    let text = std::fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
    let mut lock: PolyLock = toml::from_str(&text).with_context(|| format!("parsing {}", path.display()))?;
    if lock.version != LOCK_VERSION {
        bail!(
            "unsupported {LOCK_FILE_NAME} version {}; expected {LOCK_VERSION}",
            lock.version
        );
    }
    lock.normalize();
    Ok(Some(lock))
}

/// Atomically write `<root>/poly.lock`, or remove it when `lock` is empty.
pub fn write(root: &Path, lock: &PolyLock) -> anyhow::Result<()> {
    let path = root.join(LOCK_FILE_NAME);
    if lock.is_empty() {
        if path.is_file() {
            std::fs::remove_file(&path).with_context(|| format!("removing {}", path.display()))?;
        }
        return Ok(());
    }
    let temporary = root.join(format!("{LOCK_FILE_NAME}.tmp"));
    std::fs::write(&temporary, lock.to_toml()?).with_context(|| format!("writing {}", temporary.display()))?;
    std::fs::rename(&temporary, &path).with_context(|| format!("installing {}", path.display()))
}

/// A sentence fragment to append to a "no lock entry" error: names a legacy lock
/// file that exists while `poly.lock` does not, and empty otherwise.
pub fn legacy_hint(root: &Path) -> String {
    if root.join(LOCK_FILE_NAME).is_file() {
        return String::new();
    }
    let found: Vec<&str> = LEGACY_LOCK_FILE_NAMES
        .iter()
        .copied()
        .filter(|name| root.join(name).is_file())
        .collect();
    if found.is_empty() {
        String::new()
    } else {
        format!(
            " ({} is no longer read; `poly lock` writes {LOCK_FILE_NAME} in its place)",
            found.join(" and ")
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn extends(git: &str, revision: &str) -> LockedExtends {
        LockedExtends {
            git: git.to_string(),
            file: "poly.toml".to_string(),
            revision: revision.to_string(),
            locked: "a".repeat(40),
        }
    }

    fn hook(id: &str) -> LockedHookSource {
        LockedHookSource {
            id: id.to_string(),
            source: format!("https://example.invalid/{id}.git"),
            revision: "b".repeat(40),
            path: format!("cache://hook-sources/key/{id}"),
        }
    }

    fn tool(name: &str) -> LockedTool {
        LockedTool {
            name: name.to_string(),
            version: "1.2.3".to_string(),
            assets: ["linux-x86_64", "darwin-aarch64"]
                .iter()
                .map(|platform| LockedAsset {
                    platform: (*platform).to_string(),
                    url: format!("https://example.invalid/{name}-{platform}"),
                    sha256: "d".repeat(64),
                    member: None,
                })
                .collect(),
        }
    }

    #[test]
    fn round_trips_and_orders_deterministically() {
        let dir = tempfile::tempdir().unwrap();
        let lock = PolyLock {
            version: LOCK_VERSION,
            extends: vec![
                extends("https://z.invalid/a.git", "main"),
                extends("https://a.invalid/a.git", "main"),
            ],
            hook_sources: vec![hook("zeta"), hook("alpha")],
            tools: vec![tool("zig"), tool("actionlint")],
        };
        write(dir.path(), &lock).unwrap();
        let text = std::fs::read_to_string(dir.path().join(LOCK_FILE_NAME)).unwrap();
        assert!(text.starts_with(HEADER));
        assert!(text.find("a.invalid").unwrap() < text.find("z.invalid").unwrap());
        assert!(text.find("alpha").unwrap() < text.find("zeta").unwrap());
        assert!(text.find("actionlint").unwrap() < text.find("\"zig\"").unwrap());

        let read_back = read(dir.path()).unwrap().unwrap();
        let mut expected = lock.clone();
        expected.normalize();
        assert_eq!(read_back, expected);

        write(dir.path(), &read_back).unwrap();
        assert_eq!(std::fs::read_to_string(dir.path().join(LOCK_FILE_NAME)).unwrap(), text);
    }

    #[test]
    fn empty_lock_removes_the_file() {
        let dir = tempfile::tempdir().unwrap();
        write(
            dir.path(),
            &PolyLock {
                hook_sources: vec![hook("a")],
                ..PolyLock::default()
            },
        )
        .unwrap();
        assert!(dir.path().join(LOCK_FILE_NAME).is_file());
        write(dir.path(), &PolyLock::default()).unwrap();
        assert!(!dir.path().join(LOCK_FILE_NAME).exists());
    }

    #[test]
    fn rejects_unsupported_version_and_unknown_keys() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join(LOCK_FILE_NAME);
        std::fs::write(&path, "version = 2\n").unwrap();
        assert!(read(dir.path()).unwrap_err().to_string().contains("unsupported"));
        std::fs::write(&path, "version = 1\nsources = []\n").unwrap();
        assert!(read(dir.path()).is_err());
    }

    #[test]
    fn legacy_files_are_never_read_but_hinted() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(dir.path().join("poly-hooks.lock"), "version = 1\n").unwrap();
        assert!(read(dir.path()).unwrap().is_none());
        let hint = legacy_hint(dir.path());
        assert!(hint.contains("poly-hooks.lock") && hint.contains("poly lock"), "{hint}");
        std::fs::write(dir.path().join(LOCK_FILE_NAME), "version = 1\n").unwrap();
        assert_eq!(legacy_hint(dir.path()), "");
    }
}
